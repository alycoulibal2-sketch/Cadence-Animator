#!/usr/bin/env node
// Regenerates the keyboard-shortcut reference in site/docs.html straight from
// app.js's own command registrations, so the published list can never drift from
// what the app actually binds.
//
//   node site/tools/gen-shortcuts.js          # rewrite site/docs.html in place
//   node site/tools/gen-shortcuts.js --check  # fail if it is out of date (CI)
//
// Run it after any keybind change, as part of cutting a release.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const APP_JS = path.join(ROOT, 'renderer', 'js', 'app.js');
const DOCS = path.join(ROOT, 'site', 'docs.html');
const BEGIN = '<!-- SHORTCUTS:BEGIN — generated by site/tools/gen-shortcuts.js, do not hand-edit -->';
const END = '<!-- SHORTCUTS:END -->';

const src = fs.readFileSync(APP_JS, 'utf8');

// Commands are registered as C({ title, shortcut, hint, section, run }).
const calls = [...src.matchAll(/\n\s*C\(\{([\s\S]*?)\}\);/g)].map((m) => m[1]);
const field = (body, name) => {
  const re = new RegExp(name + ":\\s*'((?:[^'\\\\]|\\\\.)*)'");
  const m = re.exec(body);
  return m ? m[1].replace(/\\'/g, "'") : null;
};
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const items = calls
  .map((b) => ({
    title: field(b, 'title'),
    shortcut: field(b, 'shortcut'),
    hint: field(b, 'hint'),
    section: field(b, 'section') || 'General',
  }))
  .filter((x) => x.shortcut && x.title);

// Keep the app's own grouping order rather than alphabetising — it follows how
// you actually work: playback, then posing, then the timeline, then the project.
const ORDER = ['Playback', 'Animating', 'Timeline', 'Onion skin', 'Add', 'Import', 'Export', 'Project', 'General'];

const bySection = {};
for (const it of items) (bySection[it.section] = bySection[it.section] || []).push(it);

const unknown = Object.keys(bySection).filter((s) => !ORDER.includes(s));
if (unknown.length) {
  console.error('gen-shortcuts: new section(s) with no place in ORDER: ' + unknown.join(', '));
  console.error('Add them to ORDER in this file so they are not silently dropped.');
  process.exit(1);
}

// "Ctrl+S / Numpad 0" is one command with two bindings; "→ / Numpad 6" likewise.
// Split on " / " into separate key runs, and each run on "+" into separate keys.
//
// The "+" is only a modifier separator when written tight against both
// neighbours: in "Ctrl+X" it joins two keys, but in "Numpad +" it *is* the key.
// Splitting blindly produced an empty <kbd> for that one.
function kbds(shortcut) {
  return shortcut
    .split(' / ')
    .map((alt) => {
      const t = alt.trim();
      const keys = /(\s\+|\+\s)/.test(t) ? [t] : t.split('+');
      return keys.map((k) => `<kbd>${esc(k.trim())}</kbd>`).join('');
    })
    .join('<span class="muted" style="font-size:0.78rem"> or </span>');
}

let block = '';
for (const section of ORDER) {
  const rows = bySection[section];
  if (!rows) continue;
  // h3, not h4: these are subsections of the Shortcuts <h2>, and skipping a
  // level breaks the document outline for screen-reader users.
  block += `        <div class="keys-group">\n          <h3>${esc(section)}</h3>\n          <div class="keys-list">\n`;
  for (const r of rows) {
    const label = r.hint
      ? `${esc(r.title)} <span class="muted">— ${esc(r.hint)}</span>`
      : esc(r.title);
    block += `            <div><span>${label}</span><span class="kbds">${kbds(r.shortcut)}</span></div>\n`;
  }
  block += '          </div>\n        </div>\n\n';
}

let docs = fs.readFileSync(DOCS, 'utf8');
const i = docs.indexOf(BEGIN);
const j = docs.indexOf(END);
if (i === -1 || j === -1 || j < i) {
  console.error('gen-shortcuts: could not find the SHORTCUTS:BEGIN/END markers in site/docs.html');
  process.exit(1);
}

const next =
  docs.slice(0, i + BEGIN.length) + '\n' + block + '        ' + docs.slice(j);

// The filter placeholder and the prose both quote the count; keep them honest
// rather than leaving a stale number next to a regenerated list.
const withCount = next
  .replace(/placeholder="Filter \d+ shortcuts…"/, `placeholder="Filter ${items.length} shortcuts…"`)
  .replace(/all \d+ commands, including/, `all ${calls.length} commands, including`);

if (process.argv.includes('--check')) {
  if (withCount !== docs) {
    console.error('gen-shortcuts: site/docs.html is out of date. Run: node site/tools/gen-shortcuts.js');
    process.exit(1);
  }
  console.log(`gen-shortcuts: up to date (${items.length} shortcuts, ${calls.length} commands).`);
  process.exit(0);
}

fs.writeFileSync(DOCS, withCount);
console.log(
  `gen-shortcuts: wrote ${items.length} shortcuts across ${ORDER.filter((s) => bySection[s]).length} sections ` +
  `into site/docs.html (${calls.length} commands total).`
);
